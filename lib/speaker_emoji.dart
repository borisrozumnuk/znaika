/// Эмодзи голоса по номеру с нуля; если эмодзи кончились — по кругу с номером круга.
String speakerEmojiFor(int index) {
  final emoji = speakerEmoji[index % speakerEmoji.length];
  final round = index ~/ speakerEmoji.length;
  return round == 0 ? emoji : '$emoji${round + 1}';
}

final _label = RegExp(r'^Собеседник (\d+)$');

/// Подпись собеседника для показа: «Собеседник 2» → 🐻, остальное (имя, «Я», «Собеседники») — как есть.
String displaySpeaker(String label) => switch (_label.firstMatch(label.trim())) {
      final m? => speakerEmojiFor(int.parse(m[1]!) - 1),
      _ => label,
    };

/// Метки «Собеседник N» в тексте (и склонённые Gemma: «Собеседнику 2», «с Собеседником 3»)
/// → эмодзи. «Собеседники» без номера не трогает.
String withSpeakerEmoji(String text) => text.replaceAllMapped(
      RegExp(r'(?<![\p{L}\p{N}])Собеседник(?:а|у|ом|е)?\s+(\d+)(?!\d)', unicode: true),
      (m) => speakerEmojiFor(int.parse(m[1]!) - 1),
    );
