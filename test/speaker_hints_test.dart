import 'package:flutter_test/flutter_test.dart';
import 'package:znaika/speaker_hints.dart';

void main() {
  test('обращения: усечённые формы, после запятой, в начале фразы', () {
    expect(vocatives('Слушай, Кость, возьмёшь?'), ['Костя']);
    expect(vocatives('Лёш, у тебя всё готово?'), ['Лёша']);
    expect(vocatives('Давай, Вадим, расскажи про тесты.'), ['Вадим']);
    expect(vocatives('С макетами всё понятно, Костя.'), ['Костя']);
    expect(vocatives('Анна, начнёшь с платёжки?'), ['Анна']);
  });

  test('упоминания в третьем лице — не обращения', () {
    expect(vocatives('Отчёт вчера прислал Руслан. Спасибо ему.'), isEmpty);
    expect(vocatives('К четвергу успеем, если Игорь поднимет стенд до среды.'), isEmpty);
    expect(vocatives('Марина из финансов должна прислать лимиты.'), isEmpty);
    // Слова, которые чаще не имя, в словарь не входят.
    expect(vocatives('Слава, богу, успели.'), isEmpty);
  });

  test('подсказка: ответивший после обращения голос', () {
    final hints = suggestSpeakerNames([
      '[00:00] Я: Коллеги, добрый день. Олег, что с вакансиями?',
      '[00:06] Собеседник 1: Вакансию опубликовали.',
      '[00:18] Собеседник 2: Марина из финансов пришлёт лимиты к среде.',
      '[00:31] Я: Спасибо. Ира, проведёшь собеседование?',
      '[00:35] Собеседник 2: Да, давайте я.',
    ]);
    expect({for (final h in hints) h.speaker: h.name}, {'Собеседник 1': 'Олег', 'Собеседник 2': 'Ира'});
    expect(hints.first.evidence, contains('Олег, что с вакансиями?'));
  });

  test('имя одному голосу; разнобой ответов — без подсказки; уже названным — нет', () {
    final hints = suggestSpeakerNames([
      '[00:00] Я: Лёш, у тебя всё готово?',
      '[00:03] Собеседник 1: Один.',
      '[00:10] Я: Лёш, а репозиторий?',
      '[00:12] Собеседник 2: Тоже один.',
      '[00:20] Я: Лёш, всё понятно?',
      '[00:22] Собеседник 3: Да.',
      '[00:30] Собеседник 1: Костя, возьмёшь?',
      '[00:33] Костя: Могу.',
    ]);
    expect(hints, isEmpty);
  });

  test('после реплики того же говорящего ждём ответа другого, но не дольше 30 с', () {
    final hints = suggestSpeakerNames([
      '[00:00] Я: Дима, расскажешь?',
      '[00:02] Я: Что там с оплатой.',
      '[00:05] Собеседник 1: Падали платежи.',
      '[01:00] Я: Света, а у тебя?',
      '[01:45] Собеседник 2: Всё хорошо.',
    ]);
    expect({for (final h in hints) h.speaker: h.name}, {'Собеседник 1': 'Дима'});
  });
}
