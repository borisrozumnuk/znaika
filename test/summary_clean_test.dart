import 'package:flutter_test/flutter_test.dart';
import 'package:znaika/summarizer.dart';

void main() {
  test('первый проход: лишний раздел «Задачи», повторы пунктов и «(Часть N)» убираются', () {
    const raw = '''## Кратко
Обсудили релиз.

## Обсуждение
*   **DLC и автоматизация (Часть 3-6):**
    *   Конвейер локальный [1:16:58].

## Решения
*   Разделить трек на два направления [1:08:27].
*   Встретиться в понедельник [1:14:17].
*   Разделить трек на два направления [1:08:27].

## Задачи
*   **Собеседник 1:** Подключить бота [16:56].''';
    final clean = cleanSummary(raw, sections: ['Кратко', 'Обсуждение', 'Решения']);
    expect(clean, isNot(contains('Задачи')));
    expect(clean, contains('**DLC и автоматизация:**'));
    expect('Разделить трек'.allMatches(clean), hasLength(1));
    expect(clean, contains('Встретиться в понедельник'));
  });

  test('второй проход: задачи и вопросы остаются', () {
    const raw = '''## Задачи
- [ ] Собеседник 1 — подключить бота [16:56]

## Открытые вопросы
- Как валидировать агентов? [26:27]''';
    expect(cleanSummary(raw, sections: ['Задачи', 'Открытые вопросы']), raw);
  });
}
